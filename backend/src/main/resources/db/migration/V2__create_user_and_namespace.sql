-- Etapa 2: usuarios autenticados con Google y su espacio de nombres (ver ADR-0028 y ADR-0029).
-- La unicidad del espacio se garantiza en la base: un nombre por espacio y un espacio por usuario.
-- La tabla link no cambia en este paso: los enlaces anónimos siguen igual.

CREATE TABLE app_user (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    google_sub  VARCHAR(255) NOT NULL,
    email       VARCHAR(320),
    name        VARCHAR(255),
    created_at  TIMESTAMP(6) NOT NULL,
    CONSTRAINT uk_app_user_google_sub UNIQUE (google_sub)
);

-- name: solo minúsculas y números, hasta 15 caracteres (límite técnico del equipo, ADR-0029).
CREATE TABLE namespace (
    id       BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name     VARCHAR(15) NOT NULL,
    user_id  BIGINT      NOT NULL,
    CONSTRAINT uk_namespace_name UNIQUE (name),
    CONSTRAINT uk_namespace_user UNIQUE (user_id),
    CONSTRAINT fk_namespace_user FOREIGN KEY (user_id) REFERENCES app_user (id),
    CONSTRAINT ck_namespace_name CHECK (REGEXP_MATCHES(name, '[a-z0-9]+'))
);
