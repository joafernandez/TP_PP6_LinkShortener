-- Etapa 2, parte C: pedidos de login con QR desde el celular (ver ADR-0033).
-- code: va dentro del QR y lo ve el celular. secret: solo lo conoce la computadora que pidió el login.
-- Un pedido vence a los pocos minutos y se usa una sola vez: la transición AUTHORIZED -> USED es atómica.
-- Si se borra el usuario, se borran sus pedidos.
CREATE TABLE qr_login (
	id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
	code       VARCHAR(64)  NOT NULL,
	secret     VARCHAR(64)  NOT NULL,
	status     VARCHAR(12)  NOT NULL,
	user_id    BIGINT,
	created_at TIMESTAMP(6) NOT NULL,
	expires_at TIMESTAMP(6) NOT NULL,
	CONSTRAINT uk_qr_login_code UNIQUE (code),
	CONSTRAINT fk_qr_login_user FOREIGN KEY (user_id) REFERENCES app_user (id) ON DELETE CASCADE,
	CONSTRAINT ck_qr_login_status CHECK (status IN ('PENDING', 'AUTHORIZED', 'REJECTED', 'USED'))
);
