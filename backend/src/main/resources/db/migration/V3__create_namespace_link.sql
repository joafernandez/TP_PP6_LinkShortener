-- Etapa 2: enlaces dentro del espacio de un usuario, /{espacio}/{código} (ver ADR-0032).
-- Tabla aparte de link: los enlaces anónimos y su alias UNIQUE global no cambian.
-- El código es único solo dentro de cada espacio; un código vencido se reasigna actualizando su fila (ADR-0021).
-- alias: minúsculas, números, - y _, hasta 15 caracteres (límite técnico del equipo, ADR-0029).
-- ON DELETE CASCADE: si se borrara un espacio, sus enlaces no tendrían a qué pertenecer.

CREATE TABLE namespace_link (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    namespace_id  BIGINT        NOT NULL,
    alias         VARCHAR(15)   NOT NULL,
    original_url  VARCHAR(2048) NOT NULL,
    created_at    TIMESTAMP(6)  NOT NULL,
    expires_at    TIMESTAMP(6)  NOT NULL,
    CONSTRAINT uk_namespace_link_alias UNIQUE (namespace_id, alias),
    CONSTRAINT fk_namespace_link_namespace FOREIGN KEY (namespace_id) REFERENCES namespace (id) ON DELETE CASCADE,
    CONSTRAINT ck_namespace_link_alias CHECK (REGEXP_MATCHES(alias, '[a-z0-9_-]+'))
);
