-- Etapa 2: todos los nombres de un espacio, el principal y los que están en transición (ver ADR-0034).
-- Como todos comparten la columna name con UNIQUE, la base impide que dos espacios tengan o
-- reserven el mismo nombre, aunque lleguen pedidos simultáneos.
-- expires_at NULL: nombre principal. Con fecha: nombre anterior, que funciona y queda reservado hasta ese momento.
-- namespace.name sigue guardando el nombre principal (ADR-0028).

CREATE TABLE namespace_name (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    namespace_id  BIGINT       NOT NULL,
    name          VARCHAR(15)  NOT NULL,
    expires_at    TIMESTAMP(6),
    CONSTRAINT uk_namespace_name_value UNIQUE (name),
    CONSTRAINT fk_namespace_name_namespace FOREIGN KEY (namespace_id) REFERENCES namespace (id) ON DELETE CASCADE,
    CONSTRAINT ck_namespace_name_value CHECK (REGEXP_MATCHES(name, '[a-z0-9]+'))
);

-- Los espacios existentes pasan a tener su nombre actual como principal.
INSERT INTO namespace_name (namespace_id, name, expires_at)
SELECT id, name, NULL FROM namespace;
